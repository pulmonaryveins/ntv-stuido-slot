-- Studio Slots: core schema.
-- No Adobe credentials are ever stored here. Slots only track who is using a seat.

create schema if not exists private;

-- ---------------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------------
create type public.app_role as enum ('admin', 'user');
create type public.work_role as enum ('editor', 'designer', 'motion');
create type public.slot_status as enum (
  'designing', 'editing', 'color_grading', 'motion', 'rendering', 'break'
);

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------
create table public.profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  name         text not null check (char_length(name) between 1 and 60),
  role         public.app_role not null default 'user',
  work_role    public.work_role not null default 'designer',
  active       boolean not null default true,
  avatar_color text not null default '#e07a5f' check (avatar_color ~ '^#[0-9a-fA-F]{6}$'),
  created_at   timestamptz not null default now()
);

create table public.accounts (
  id    integer generated by default as identity primary key,
  label text not null unique check (char_length(label) between 1 and 40)
);

create table public.slots (
  id             integer generated by default as identity primary key,
  account_id     integer not null references public.accounts (id) on delete cascade,
  slot_number    smallint not null check (slot_number > 0),
  user_id        uuid references public.profiles (id),
  status         public.slot_status,
  claimed_at     timestamptz,
  expected_until timestamptz,
  render_eta     timestamptz,
  hold_user_id   uuid references public.profiles (id),
  hold_until     timestamptz,
  prev_status    public.slot_status,
  break_until    timestamptz,
  unique (account_id, slot_number),
  constraint slots_occupied_consistent check (
    (user_id is null and status is null and claimed_at is null and expected_until is null
      and render_eta is null and prev_status is null and break_until is null)
    or (user_id is not null and status is not null and claimed_at is not null
      and expected_until is not null)
  ),
  constraint slots_render_eta_only_rendering check (render_eta is null or status = 'rendering'),
  constraint slots_break_until_iff_break check ((status = 'break') = (break_until is not null)),
  constraint slots_prev_status_iff_break check ((status = 'break') = (prev_status is not null)),
  constraint slots_prev_status_not_break check (prev_status is distinct from 'break'),
  constraint slots_hold_pair check ((hold_user_id is null) = (hold_until is null)),
  constraint slots_hold_only_when_free check (hold_user_id is null or user_id is null)
);

-- One user holds at most one seat and at most one reservation.
create unique index slots_one_seat_per_user on public.slots (user_id) where user_id is not null;
create unique index slots_one_hold_per_user on public.slots (hold_user_id) where hold_user_id is not null;

create table public.queue (
  id        bigint generated always as identity primary key,
  user_id   uuid not null unique references public.profiles (id) on delete cascade,
  joined_at timestamptz not null default now()
);
create index queue_order_idx on public.queue (joined_at, id);

-- user_id = actor (null = system/cron). meta.target_user_id = person to notify, if any.
create table public.activity_log (
  id         bigint generated always as identity primary key,
  slot_id    integer references public.slots (id) on delete set null,
  user_id    uuid references public.profiles (id) on delete set null,
  action     text not null,
  meta       jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index activity_log_created_idx on public.activity_log (created_at desc);
create index activity_log_user_idx on public.activity_log (user_id, created_at desc);
create index activity_log_slot_idx on public.activity_log (slot_id, created_at desc);
create index activity_log_action_idx on public.activity_log (action, created_at desc);

create table public.settings (
  id              boolean primary key default true check (id),
  max_session_min integer not null default 240 check (max_session_min between 15 and 1440),
  hold_minutes    integer not null default 10 check (hold_minutes between 1 and 120),
  break_minutes   integer not null default 15 check (break_minutes between 1 and 120)
);
insert into public.settings default values;

