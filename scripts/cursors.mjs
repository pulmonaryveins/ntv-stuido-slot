function svg(art) {
  const g = art.trim().split('\n')
  if (g.length !== N || g.some((r) => r.length !== N)) throw new Error('sprites must be 16x16')
  const filled = (x, y) => g[y]?.[x] !== undefined && g[y][x] !== '.'
  const rects = []
  for (let y = 0; y < N - 1; y++)
    for (let x = 0; x < N - 1; x++)
      if (filled(x, y) && !filled(x + 1, y + 1)) rects.push(`<rect x="${x + 1}" y="${y + 1}" width="1" height="1" fill="${SHADOW}"/>`)
  for (let y = 0; y < N; y++)
    for (let x = 0; x < N; x++) {
      const c = g[y][x]
      if (c === '.') continue
      if (!PALETTE[c]) throw new Error(`unknown colour ${c}`)
      rects.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${PALETTE[c]}"/>`)
    }
  const px = N * CELL
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="0 0 ${N} ${N}" shape-rendering="crispEdges">${rects.join('')}</svg>\n`
}

mkdirSync('public/cursors', { recursive: true })
for (const [name, { art, hot }] of Object.entries(SPRITES)) {
  writeFileSync(`public/cursors/${name}.svg`, svg(art))
  console.log(`\n${name}  hotspot ${hot[0] * CELL} ${hot[1] * CELL}`)
  for (const row of art.trim().split('\n')) console.log(row.replace(/\./g, ' '))
}
